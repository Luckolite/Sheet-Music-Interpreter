package io.github.luckolite.interpreter;

import org.junit.Test;
import static org.junit.Assert.assertEquals;

public final class YoutubeDescriptionCreditsTest {
    private static void credits(String text, String artist, String composer, String arranger) {
        assertEquals(
                new YoutubeDescriptionCredits.Credits(artist, composer, arranger),
                YoutubeDescriptionCredits.parse(text));
    }

    @Test
    public void explicitRolesRemainSeparate() {
        credits(
                "Artist: Mara Vale\nComposer: Byron Stone\nArranger: Ada Reed",
                "Mara Vale",
                "Byron Stone",
                "Ada Reed");
    }

    @Test
    public void performedAndArrangedByCanCreditOnePersonForBothRoles() {
        credits(
                "Arranged and performed by Mara Vale\nComposed by Ada Reed",
                "Mara Vale",
                "Ada Reed",
                "Mara Vale");
    }

    @Test
    public void writtenAndArrangedByAlsoPreservesBothRoles() {
        credits("Written & arranged by: Ada Reed", "", "Ada Reed", "Ada Reed");
    }

    @Test
    public void instrumentPerformersAreArtistsRatherThanComposers() {
        credits(
                "Violin: Mara Vale\nPiano - Bo Reed\nMusic by Ada Stone",
                "Mara Vale; Bo Reed",
                "Ada Stone",
                "");
    }

    @Test
    public void originalCompositionAndTranscriptionLabelsAreSupported() {
        credits(
                "Original composer: Ada Reed\nTranscribed by: Bo Stone",
                "",
                "Ada Reed",
                "Bo Stone");
    }

    @Test
    public void songwriterAndMusicLyricsLabelsKeepMusicalAuthorship() {
        credits(
                "Songwriters: Ada Reed, Bo Stone\nMusic & Lyrics by: Mara Vale\nLyricist: Other Person",
                "",
                "Ada Reed; Bo Stone; Mara Vale",
                "");
    }

    @Test
    public void automaticMusicBlockCreditsTrackArtistsButNotTheDistributor() {
        credits(
                "Provided to YouTube by Fictional Records\n\nNorthern Tune · Mara Vale · Bo Reed\n\n"
                        + "Fictional Album\n\n℗ 2026 Fictional Records\nReleased on: 2026-01-01\n"
                        + "Composer, Lyricist: Ada Stone\nArranger: Mara Vale\nAuto-generated by YouTube.",
                "Mara Vale; Bo Reed",
                "Ada Stone",
                "Mara Vale");
    }

    @Test
    public void anUnlabeledMiddleDotTitleDoesNotImplyMusicCredits() {
        credits("My video · my friends\nSubscribe for more", "", "", "");
    }

    @Test
    public void aProvidedBlockWithoutATrackDoesNotConsumeTheNextCredit() {
        credits("Provided to YouTube by Fictional Label\nComposer: Ada Stone", "", "Ada Stone", "");
    }

    @Test
    public void headingsCanOwnSeveralNamesButStopAtBlankOrAnotherField() {
        credits(
                "Artists:\nMara Vale\nBo Reed\n\nAn unrelated album\nComposer:\nAda Stone\n"
                        + "Released on: 2026-01-01\nNot A Contributor",
                "Mara Vale; Bo Reed",
                "Ada Stone",
                "");
    }

    @Test
    public void standaloneRoleHeadingsAreSupported() {
        credits(
                "COMPOSERS\nAda Reed\nBo Stone\n\nARRANGERS\nMara Vale",
                "",
                "Ada Reed; Bo Stone",
                "Mara Vale");
    }

    @Test
    public void inlineCreditSectionsDoNotBecomePartOfNames() {
        credits(
                "Composer: Ada Reed; Arranger: Bo Stone | Artist: Mara Vale",
                "Mara Vale",
                "Ada Reed",
                "Bo Stone");
    }

    @Test
    public void inlineBylinesWithDifferentNamesRemainSeparate() {
        credits("Composed by Ada Reed and arranged by Bo Stone", "", "Ada Reed", "Bo Stone");
    }

    @Test
    public void duplicatesAreRemovedWithinRolesButNotAcrossRoles() {
        credits(
                "Artist: Mara Vale\nPerformed by mara vale\nArranged by Mara Vale",
                "Mara Vale",
                "",
                "Mara Vale");
    }

    @Test
    public void fullPersonListsSplitWithoutBreakingBandNames() {
        credits(
                "Artists: Ada Reed & Bo Stone\nArtist: Earth, Wind & Fire",
                "Ada Reed; Bo Stone; Earth, Wind & Fire",
                "",
                "");
    }

    @Test
    public void surnameFirstAndStageNamesKeepTheirSpelling() {
        credits("Composer: Reed, Ada\nArtist: ARKAI\nArtist: P!NK", "ARKAI; P!NK", "Reed, Ada", "");
    }

    @Test
    public void aNameBeginningWithARoleWordIsNotAnotherCreditLabel() {
        credits(
                "Artists: Mara Vale, Music Brown; Piano Guys",
                "Mara Vale; Music Brown; Piano Guys",
                "",
                "");
    }

    @Test
    public void unicodeNamesAndFullWidthLabelsArePreserved() {
        credits(
                "🎵 Artist：Björk\nComposer: 坂本龍一\nArranger: José de Vale",
                "Björk",
                "坂本龍一",
                "José de Vale");
    }

    @Test
    public void markdownAndTrailingSocialLinksRetainOnlyTheCreditedName() {
        credits(
                "Artist: [Mara Vale](https://example.invalid/mara)\n"
                        + "Composer: Ada Reed - https://example.invalid/ada\nArranger: https://example.invalid/bo",
                "Mara Vale",
                "Ada Reed",
                "");
    }

    @Test
    public void unrelatedCreditsPromotionsChannelsAndCopyrightAreNotArtists() {
        credits(
                "Uploaded by Fictional Channel\nProvided to YouTube by Label\nNo automatic track here\n"
                        + "Video: Mara Vale\nProducer: Bo Reed\nCamera: Ada Stone\n© Fictional Records\n"
                        + "Follow Composer: https://example.invalid\nArtist: Please subscribe to my channel",
                "",
                "",
                "");
    }

    @Test
    public void unknownAndEmptyCreditsStayUnresolved() {
        credits("Artist: Unknown\nComposer: N/A\nArranger: None", "", "", "");
        credits(null, "", "", "");
        credits("", "", "", "");
    }

    @Test
    public void anOverlongCreditCannotCreateAnUnboundedProfile() {
        credits("Artist: " + "X".repeat(700) + "\nComposer: Ada Reed", "", "Ada Reed", "");
    }

    @Test
    public void aDescriptionCannotLeakCreditsPastTheInputBudget() {
        credits("\n".repeat(100_000) + "Composer: Ada Reed", "", "", "");
    }

    @Test
    public void aServiceTranscriptionStaysUnresolvedWithoutErasingExplicitMusicalCredits() {
        String evidence = "Transcribed by Songscription AI";
        var result =
                YoutubeDescriptionCredits.parse(
                        "Artist: Mara Vale\nComposer: Ada Reed\n" + evidence);
        assertEquals("Mara Vale", result.artists());
        assertEquals("Ada Reed", result.composers());
        assertEquals("", result.arrangers());
        assertEquals(evidence, result.unresolved());
    }

    @Test
    public void bareServiceDomainsAndServiceOnlyLinksAreRetainedForReview() {
        for (String value :
                new String[] {
                    "songscription.com",
                    "example.ai",
                    "www.example.app",
                    "https://example.invalid/tool"
                }) {
            String evidence = "Transcription by " + value;
            var result = YoutubeDescriptionCredits.parse(evidence);
            assertEquals("", result.arrangers());
            assertEquals(evidence, result.unresolved());
        }
    }

    @Test
    public void humanTranscribersKeepNamesAndOptionalSocialLinks() {
        credits(
                "Transcribed by Ai Reed\nTranscription by Ada Stone - https://example.invalid/ada",
                "",
                "",
                "Ai Reed; Ada Stone");
    }

    @Test
    public void mixedHumanAndServiceTranscribersDoNotEraseTheHuman() {
        String evidence = "Transcribed by Ada Reed; Songscription AI";
        var result = YoutubeDescriptionCredits.parse(evidence);
        assertEquals("Ada Reed", result.arrangers());
        assertEquals(evidence, result.unresolved());
    }

    @Test
    public void serviceCreditHeadingsRetainTheirLabelAndRawPayload() {
        var result =
                YoutubeDescriptionCredits.parse(
                        "Transcription:\nAutomated transcription service\n\nComposer: Ada Reed");
        assertEquals("Ada Reed", result.composers());
        assertEquals("", result.arrangers());
        assertEquals("Transcription: Automated transcription service", result.unresolved());
    }
}
